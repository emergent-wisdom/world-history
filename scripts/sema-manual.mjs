// Renders sema/MANUAL.md, the review surface for this project's Sema patterns: each card in sema/patterns/ beside
// its commentary in sema/design_critique.json, rendered by the manual generator of the Sema release tool.json pins.
//
//   SEMA_ROOT=/path/to/sema-checkout node scripts/sema-manual.mjs
//
// SEMA_ROOT must be a checkout of the pinned Sema commit; the generator is read from it with git, unchanged.
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(fileURLToPath(new URL('..', import.meta.url)));
const pins = JSON.parse(readFileSync(join(repo, 'tool.json'), 'utf8')).sema;
const root = process.env.SEMA_ROOT;
if (!root) throw new Error(`Set SEMA_ROOT to a checkout of ${pins.repository} at ${pins.commit}.`);
const generator = execFileSync('git', ['-C', root, 'show', `${pins.commit}:scripts/generate_design_manual.py`], { encoding: 'utf8' });

const work = mkdtempSync(join(tmpdir(), 'world-history-manual-'));
try {
  for (const dir of ['scripts', 'data', 'docs/manuals']) mkdirSync(join(work, dir), { recursive: true });
  writeFileSync(join(work, 'scripts', 'generate_design_manual.py'), generator);
  cpSync(join(repo, 'sema', 'patterns'), join(work, 'data', 'vocabulary'), { recursive: true });
  cpSync(join(repo, 'sema', 'design_critique.json'), join(work, 'data', 'design_critique.json'));
  execFileSync(join(repo, '.tools', 'sema', 'bin', 'python'), ['scripts/generate_design_manual.py'], { cwd: work, stdio: 'ignore' });
  const rendered = readFileSync(join(work, 'docs', 'manuals', 'vocabulary-design.md'), 'utf8');
  const patterns = rendered.slice(rendered.indexOf('\n## Patterns\n') + 1).replaceAll('](../../data/vocabulary/', '](patterns/');
  const count = (rendered.match(/_Patterns covered: (\d+)/) ?? [])[1];
  const header = `# World History: Sema patterns

<!-- Generated by scripts/sema-manual.mjs from sema/patterns/ and sema/design_critique.json with the manual
     generator of Sema ${pins.release} (${pins.repository} at ${pins.commit.slice(0, 8)}). Do not hand-edit:
     change a card through the project vocabulary, update its commentary in the same change, and regenerate. -->

_Patterns covered: ${count}, each with a commentary entry._

These are the historical mechanisms this construction reasons with, minted into the project's own Sema vocabulary
on top of the Sema ${pins.release} full preset. Each entry shows the card (gloss, mechanism, invariants and failure
modes, which are hashed and so fix its identity) beside its design commentary: why it exists and sits in its layer,
whether it could be removed, how it is meant to be used, its tensions and tradeoffs, a critique, and its family.

They were written and reviewed against the governing principles of the
[Sema vocabulary design manual](https://github.com/${pins.repository}/blob/${pins.tag}/docs/manuals/vocabulary-design.md#governing-principles),
the [naming taxonomy](https://github.com/${pins.repository}/blob/${pins.tag}/docs/specification/naming.md) and the
[card review method](https://github.com/${pins.repository}/blob/${pins.tag}/docs/guides/review-method.md).
Prior art in the critique is from recall and unverified, as the Sema manual marks it.

---

`;
  writeFileSync(join(repo, 'sema', 'MANUAL.md'), header + patterns);
  console.log(`wrote sema/MANUAL.md (${count} patterns)`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
